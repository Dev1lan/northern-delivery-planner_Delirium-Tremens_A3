"""Fit grouped baselines and a neural surrogate; evaluate held-out networks."""

import argparse
from collections import Counter, defaultdict
import json
import math
from pathlib import Path
from time import perf_counter
import tracemalloc

import numpy as np

from .dataset import core_version
from .model import FORMAT, OUTPUTS, STRATEGIES, NetworkModel, bounded, design, forward, rank_key


def read_rows(path):
    rows = [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]
    if not rows:
        raise ValueError("Empty label file")
    first = rows[0]
    if first["core"] != core_version():
        raise ValueError("Labels were generated by another kernel")
    seen = {}
    unique = set()
    for row in rows:
        if any(row[k] != first[k] for k in ("core", "limits", "policy", "time_budget_s")):
            raise ValueError("Mixed kernels or search budgets")
        for key in (("group", row["group"]), ("input", row["input_fingerprint"]),
                    ("configuration", row["configuration_fingerprint"]), ("seed", row["seed"])):
            if key[-1] is not None and seen.setdefault(key, row["split"]) != row["split"]:
                raise ValueError(f"Split leakage: {key}")
        key = (row["scenario_id"], row["strategy"])
        if key in unique:
            raise ValueError(f"Duplicate label: {key}")
        unique.add(key)
    return rows


def usable(row):
    return (row["audit"]["status"] == "PASSED" and row["targets"] is not None
            and row["termination"] in ("SEARCH_FINISHED", "SEARCH_LIMIT"))


def targets(row):
    target = row["targets"]
    features = row["features"]
    demand = features["demand_t"]
    minimum = features["social_minimum_t"]
    cost = target["cost"]
    return [target["total_t"]/demand if demand else 0, target["on_time_share"],
            float(target["social_failed"]) if target["social_failed"] is not None else np.nan,
            target["social_deficit_t"]/minimum if minimum else np.nan,
            math.log1p(cost/demand) if cost is not None and demand else np.nan]


def matrix(rows, names, center, scale):
    x = np.array([design(r["features"], names, [r["strategy"]], center, scale)[0][0] for r in rows])
    return x, np.array([targets(r) for r in rows])


def fit_mean(x, y):
    out = []
    for i in range(len(STRATEGIES)):
        subset = y[x[:, i-len(STRATEGIES)] == 1]
        valid = np.isfinite(subset)
        out.append(np.divide(np.nansum(subset, axis=0), valid.sum(axis=0),
                             out=np.zeros(y.shape[1]), where=valid.sum(axis=0) > 0))
    return {"kind": "mean", "weights": np.array(out)}


def fit_ridge(x, y):
    x = np.column_stack((x, np.ones(len(x))))
    penalty = np.eye(x.shape[1])*8
    penalty[-1, -1] = 0
    columns = []
    for column in y.T:
        ok = np.isfinite(column)
        columns.append(np.linalg.solve(x[ok].T @ x[ok] + penalty, x[ok].T @ column[ok])
                       if ok.any() else np.zeros(x.shape[1]))
    return {"kind": "ridge", "weights": np.column_stack(columns)}


def fit_mlp(x, y, xv, yv, seed):
    import torch

    torch.set_num_threads(1)
    torch.manual_seed(seed)
    model = torch.nn.Sequential(torch.nn.Linear(x.shape[1], 64), torch.nn.ReLU(),
                                torch.nn.Linear(64, 64), torch.nn.ReLU(), torch.nn.Linear(64, y.shape[1]))
    optimizer = torch.optim.AdamW(model.parameters(), lr=.002, weight_decay=.01)
    normalizer = np.ones(y.shape[1])
    valid_cost = np.isfinite(y[:, -1])
    if valid_cost.any():
        normalizer[-1] = max(1, np.std(y[valid_cost, -1]))
    tx, ty, vx, vy = [torch.tensor(a, dtype=torch.float32) for a in (x, y/normalizer, xv, yv/normalizer)]
    generator = torch.Generator().manual_seed(seed)
    best, stale = math.inf, 0
    for _ in range(220):
        for batch in torch.randperm(len(tx), generator=generator).split(64):
            pred, truth = model(tx[batch]), ty[batch]
            mask = truth.isfinite()
            loss = (pred[mask] - truth[mask]).square().mean()
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()
        with torch.no_grad():
            mask = vy.isfinite()
            score = float((model(vx)[mask] - vy[mask]).square().mean())
        if score < best - 1e-5:
            best, stale = score, 0
            weights = {k: v.detach().numpy().copy() for k, v in model.state_dict().items()}
        else:
            stale += 1
            if stale >= 30:
                break
    artifact = {"kind": "mlp"}
    for i in range(3):
        artifact[f"w{i}"] = weights[f"{2*i}.weight"].T
        artifact[f"b{i}"] = weights[f"{2*i}.bias"]
    artifact["w2"] = artifact["w2"] * normalizer
    artifact["b2"] = artifact["b2"] * normalizer
    return artifact


def calibration(rows, pred, y):
    """Use one worst residual per family and strategy for grouped calibration."""
    residuals = defaultdict(dict)
    for row, value, truth in zip(rows, pred[:, 1], y[:, 1], strict=True):
        samples = residuals[row["strategy"]]
        group = row["group"]
        samples[group] = max(samples.get(group, 0), abs(value-truth))
    radii = {}
    for strategy, samples in residuals.items():
        errors = sorted(samples.values())
        index = math.ceil(.9*(len(errors)+1))-1
        if index < len(errors):
            radii[strategy] = float(errors[index])
    return radii


def errors(pred, truth):
    ok = np.isfinite(truth)
    if not ok.any():
        return None
    delta = pred[ok]-truth[ok]
    return {"mae": float(np.mean(abs(delta))), "rmse": float(np.sqrt(np.mean(delta**2)))}


def summarize(rows, pred, y, radii, applicable, max_log_cost):
    if not rows:
        return {"rows": 0}
    demand = np.array([r["features"]["demand_t"] for r in rows])
    minima = np.array([r["features"]["social_minimum_t"] for r in rows])
    radius = np.array([radii.get(r["strategy"], 1) for r in rows])
    covered = np.abs(pred[:, 1]-y[:, 1]) <= radius
    intervals = np.minimum(1, pred[:, 1]+radius) - np.maximum(0, pred[:, 1]-radius)
    complete = defaultdict(list)
    for i, row in enumerate(rows):
        complete[row["scenario_id"]].append(i)
    correct, regret = [], []
    for indices in complete.values():
        first = rows[indices[0]]
        expected = len(STRATEGIES) if first["currency"] else len(STRATEGIES)-1
        if len(indices) != expected:
            continue
        args = {"has_social": bool(first["features"]["social_minimum_t"]),
                "priced": bool(first["currency"] and first["features"]["demand_t"])}
        chosen = min(indices, key=lambda i: rank_key(pred[i], **args))
        best = min(indices, key=lambda i: rank_key(y[i], **args))
        correct.append(rank_key(y[chosen], **args) == rank_key(y[best], **args))
        regret.append(max(0.0, y[best, 1] - y[chosen, 1]))
    social = np.isfinite(y[:, 2])
    bins = []
    for lo in np.arange(0, 1, .2):
        take = social & (pred[:, 2] >= lo) & (pred[:, 2] < lo+.2+float(lo > .79)*1e-9)
        if take.any():
            bins.append({"rows": int(take.sum()), "predicted": float(pred[take, 2].mean()),
                         "observed": float(y[take, 2].mean())})
    cost_prediction = np.expm1(np.minimum(pred[:, 4], max_log_cost))*demand
    actual_cost = np.expm1(y[:, 4])*demand
    return {"rows": len(rows), "scenarios": len(complete),
            "on_time_share": errors(pred[:, 1], y[:, 1]),
            "on_time_t": errors(pred[:, 1]*demand, y[:, 1]*demand),
            "total_t": errors(pred[:, 0]*demand, y[:, 0]*demand),
            "social_deficit_t": errors(pred[:, 3]*minima, y[:, 3]*minima),
            "social_brier": None if not social.any() else float(np.mean((pred[social, 2]-y[social, 2])**2)),
            "social_calibration": bins,
            "cost": errors(cost_prediction, actual_cost),
            "applicable_cost": errors(cost_prediction[applicable], actual_cost[applicable]),
            "interval_coverage": float(covered.mean()), "interval_width_share": float(intervals.mean()),
            "applicable_fraction": float(applicable.mean()),
            "applicable_interval_coverage": float(covered[applicable].mean()) if applicable.any() else None,
            "ranked_scenarios": len(correct), "top_strategy_match": float(np.mean(correct)) if correct else None,
            "on_time_share_regret": float(np.mean(regret)) if regret else None}


def fit(rows, seed):
    groups = {name: [r for r in rows if r["split"] == name and usable(r)]
              for name in ("train", "validation", "calibration", "test")}
    if not all(groups.values()):
        raise ValueError("All four splits need audited, non-timeout labels")
    train, val, cal, test = (groups[k] for k in ("train", "validation", "calibration", "test"))
    names = sorted(train[0]["features"])
    samples = {r["scenario_id"]: r for r in train}
    z = np.array([[r["features"][n] for n in names] for r in samples.values()])
    center, scale = z.mean(0), z.std(0)
    # Relative scale floors keep near-constant features from dominating distances.
    scale = np.maximum(scale, np.maximum(abs(center)*.05, .02))
    train_z = (z-center)/scale
    x, y = matrix(train, names, center, scale)
    cost = y[np.isfinite(y[:, 4]), 4]
    max_log_cost = float(max(cost, default=0))
    xv, yv = matrix(val, names, center, scale)
    xc, yc = matrix(cal, names, center, scale)
    xt, yt = matrix(test, names, center, scale)
    nearest = lambda xs: np.array([np.min(np.linalg.norm(train_z-z, axis=1)) for z in xs])
    threshold = float(np.quantile(nearest(xv[:, :len(names)]), .95))
    applicable = nearest(xt[:, :len(names)]) <= threshold
    metrics = {"counts": {k: len(v) for k, v in groups.items()},
               "termination": dict(Counter(r["termination"] for r in rows)),
               "audit_status": dict(Counter(r["audit"]["status"] for r in rows)), "models": {}}
    artifacts = {}
    for model in (fit_mean(x, y), fit_ridge(x, y), fit_mlp(x, y, xv, yv, seed)):
        kind = model["kind"]
        pv = bounded(forward(model, xv))
        radii = calibration(cal, bounded(forward(model, xc)), yc)
        pt = bounded(forward(model, xt))
        start = perf_counter()
        for _ in range(150):
            bounded(forward(model, xt[:len(STRATEGIES)]))
        elapsed = (perf_counter()-start)/150
        tracemalloc.start()
        bounded(forward(model, xt[:len(STRATEGIES)]))
        _, peak = tracemalloc.get_traced_memory()
        tracemalloc.stop()
        metrics["models"][kind] = {"validation": summarize(val, pv, yv, radii, np.ones(len(val), dtype=bool), max_log_cost),
                                   "test": summarize(test, pt, yt, radii, applicable, max_log_cost),
                                   "forward_ms_per_scenario": elapsed*1000, "forward_peak_bytes": peak,
                                   "by_family": {}}
        for family in sorted({r["family"] for r in test}):
            mask = np.array([r["family"] == family for r in test])
            metrics["models"][kind]["by_family"][family] = summarize(
                [r for r, keep in zip(test, mask, strict=True) if keep], pt[mask], yt[mask], radii, applicable[mask], max_log_cost)
        artifacts[kind] = (model, radii)
    def validation_error(kind):
        result = metrics["models"][kind]["validation"]
        return result["on_time_share"]["mae"] + result["total_t"]["mae"] / max(1, np.mean([r["features"]["demand_t"] for r in val]))
    selected = min(artifacts, key=validation_error)
    metrics["selected"] = selected

    first = train[0]
    social = y[np.isfinite(y[:, 2]), 2]
    meta = {"format": FORMAT, "kind": selected, "features": names, "outputs": OUTPUTS, "seed": seed,
            "core": first["core"], "limits": first["limits"], "policy": first["policy"],
            "ood_threshold": threshold, "interval_radii": artifacts[selected][1],
            "currencies": sorted({r["currency"] for r in train if r["currency"] is not None}),
            "social_trained": bool(len(social) >= 30 and len(np.unique(social)) == 2),
            "cost_trained": bool(len(cost) >= 30), "max_log_cost": max_log_cost}
    metrics["metadata"] = meta
    candidates = {}
    for kind, (model, model_radii) in artifacts.items():
        model_meta = dict(meta, kind=kind, interval_radii=model_radii)
        candidates[kind] = dict(model, meta=np.array(json.dumps(model_meta)),
                                mean=center, scale=scale, train_z=train_z)
    return candidates, metrics


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("labels", type=Path)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--metrics", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=37)
    args = parser.parse_args(argv)
    candidates, metrics = fit(read_rows(args.labels), args.seed)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(args.out, **candidates[metrics["selected"]])
    np.savez_compressed(args.out.with_name(args.out.stem + "_mlp.npz"), **candidates["mlp"])
    NetworkModel.load(args.out)
    args.metrics.write_text(json.dumps(metrics, indent=2, allow_nan=False)+"\n", encoding="utf-8")
    print(f"Selected {metrics['selected']}; {metrics['counts']}")


if __name__ == "__main__":
    main()
